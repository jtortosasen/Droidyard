// Generates src/lib/api/capabilities.gen.ts from schema/capabilities.json, the published
// contract (ADR-0040 §4; plan m2a step 2). The output is not committed: every frontend
// `check` and `build` regenerates it, so a schema change that breaks a field the UI reads
// fails `check` before it reaches a user.
//
// One schema is composed from the contract and compiled once: a `Capabilities` interface
// whose keys are capability names and whose values are `{ params, result }`. A capability
// that is longRunning answers with an operation envelope; its `result` is the schema's
// `output.properties.result`, not `output`. A descriptor field the UI does not read yet
// (event payloads, step 4) joins the per-capability object in `entryFor`, nothing else.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const root = new URL('../../', import.meta.url);
const source = new URL('schema/capabilities.json', root);
const target = new URL('web/src/lib/api/capabilities.gen.ts', root);

interface Descriptor {
	name: string;
	scope: string;
	statefulness: string;
	longRunning?: boolean;
	input: Record<string, unknown>;
	output?: { properties?: { result?: Record<string, unknown> } } & Record<string, unknown>;
}

const contract: { version: string; capabilities: Descriptor[] } = JSON.parse(
	readFileSync(source, 'utf8'),
);

/** The parameters and the result type of one capability. */
function entryFor(d: Descriptor): Record<string, unknown> {
	const result = d.longRunning ? d.output?.properties?.result : d.output;
	if (!result) throw new Error(`${d.name}: the descriptor has no ${d.longRunning ? 'output.properties.result' : 'output'}`);
	return {
		type: 'object',
		additionalProperties: false,
		required: ['params', 'result'],
		properties: { params: d.input, result },
	};
}

const composed = {
	title: 'Capabilities',
	description: `Every capability's parameters and result, from schema/capabilities.json ${contract.version}.`,
	type: 'object',
	additionalProperties: false,
	required: contract.capabilities.map((d) => d.name),
	properties: Object.fromEntries(contract.capabilities.map((d) => [d.name, entryFor(d)])),
};

const types = await compile(composed as never, 'Capabilities', {
	bannerComment: '',
	additionalProperties: false,
	format: true,
	style: { useTabs: true, singleQuote: true },
	unreachableDefinitions: false,
	strictIndexSignatures: false,
});

// What the client branches on, from the descriptors (never typed by hand).
const info = Object.fromEntries(
	contract.capabilities.map((d) => [
		d.name,
		{ scope: d.scope, longRunning: d.longRunning === true, statefulness: d.statefulness },
	]),
);

const out = `// GENERATED by web/scripts/gen-client.ts from schema/capabilities.json. Do not edit; not committed.
/* eslint-disable */

export const schemaVersion = ${JSON.stringify(contract.version)};

${types.trim()}

export type CapabilityName = keyof Capabilities;
export type Params<N extends CapabilityName> = Capabilities[N]['params'];
export type Result<N extends CapabilityName> = Capabilities[N]['result'];

/** What the client branches on, per capability. */
export const capabilityInfo = ${JSON.stringify(info, null, '\t')} as const satisfies Record<
	CapabilityName,
	{ scope: 'global' | 'workspace'; longRunning: boolean; statefulness: 'stateless' | 'stateful' | 'streaming' }
>;
`;

mkdirSync(dirname(fileURLToPath(target)), { recursive: true });
writeFileSync(target, out);
console.log(`gen-client: ${contract.capabilities.length} capabilities, schema ${contract.version}`);
