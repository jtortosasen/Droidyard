// Generates src/lib/api/capabilities.gen.ts from schema/capabilities.json, the published
// contract (ADR-0040 §4; plan m2a step 2). The output is not committed: every frontend
// `check` and `build` regenerates it, so a schema change that breaks a field the UI reads
// fails `check` before it reaches a user.
//
// One schema is composed from the contract and compiled once: a `Capabilities` interface
// whose keys are capability names and whose values are `{ params, result }`. A capability
// that is longRunning answers with an operation envelope; its `result` is the schema's
// `output.properties.result`, not `output`. A second interface, `CapabilityEvents`, types
// the events a capability's own stream publishes (ADR-0041 §4): keys are capability names,
// values map an event type to its payload. A descriptor field the UI does not read yet
// joins `entryFor` (or the events composition), nothing else.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const root = new URL('../../', import.meta.url);
const source = new URL('schema/capabilities.json', root);
const target = new URL('web/src/lib/api/capabilities.gen.ts', root);

interface Descriptor {
	name: string;
	scope: string;
	statefulness: string;
	longRunning?: boolean;
	input: Record<string, unknown>;
	output?: { properties?: { result?: Record<string, unknown> } } & Record<string, unknown>;
	events?: { topic: string; types: Record<string, Record<string, unknown>> };
}

const contract: { version: string; capabilities: Descriptor[] } = JSON.parse(
	readFileSync(source, 'utf8'),
);

/** The parameters and the result type of one capability. */
function entryFor(d: Descriptor): Record<string, unknown> {
	const result = d.longRunning ? d.output?.properties?.result : d.output;
	if (!result) throw new Error(`${d.name}: the descriptor has no ${d.longRunning ? 'output.properties.result' : 'output'}`);
	return {
		type: 'object',
		additionalProperties: false,
		required: ['params', 'result'],
		properties: { params: d.input, result },
	};
}

const composed = {
	title: 'Capabilities',
	description: `Every capability's parameters and result, from schema/capabilities.json ${contract.version}.`,
	type: 'object',
	additionalProperties: false,
	required: contract.capabilities.map((d) => d.name),
	properties: Object.fromEntries(contract.capabilities.map((d) => [d.name, entryFor(d)])),
};

const withEvents = contract.capabilities.filter((d) => d.events);

/** Per capability that streams: its event types, each with its payload schema. */
function eventsFor(d: Descriptor): Record<string, unknown> {
	const types = d.events?.types ?? {};
	return {
		type: 'object',
		additionalProperties: false,
		required: Object.keys(types),
		properties: types,
	};
}

const composedEvents = {
	title: 'CapabilityEvents',
	description: `The events a capability's own stream publishes, by capability and event type, from schema/capabilities.json ${contract.version}.`,
	type: 'object',
	additionalProperties: false,
	required: withEvents.map((d) => d.name),
	properties: Object.fromEntries(withEvents.map((d) => [d.name, eventsFor(d)])),
};

// The progress a long-running call reports, which is also the payload of an
// `operation.progress` event (the same capability.Progress; plan m2b D12). Read from the
// first long-running descriptor's operation view, so it is never typed by hand.
const progressSchema = contract.capabilities
	.filter((d) => d.longRunning)
	.map((d) => (d.output?.properties as Record<string, unknown> | undefined)?.progress)
	.find((p) => p !== undefined);
if (!progressSchema) throw new Error('no long-running descriptor carries an operation view with progress');

const options = {
	bannerComment: '',
	additionalProperties: false,
	format: true,
	style: { useTabs: true, singleQuote: true },
	unreachableDefinitions: false,
	strictIndexSignatures: false,
} as const;

const types = await compile(composed as never, 'Capabilities', options);
const eventTypes = await compile(composedEvents as never, 'CapabilityEvents', options);
const progressType = await compile(
	{ ...(progressSchema as object), title: 'OperationProgress' } as never,
	'OperationProgress',
	options,
);

// The topic each streaming capability's events carry, from the descriptors.
const eventTopics = Object.fromEntries(withEvents.map((d) => [d.name, d.events?.topic]));

// What the client branches on, from the descriptors (never typed by hand).
const info = Object.fromEntries(
	contract.capabilities.map((d) => [
		d.name,
		{ scope: d.scope, longRunning: d.longRunning === true, statefulness: d.statefulness },
	]),
);

const out = `// GENERATED by web/scripts/gen-client.ts from schema/capabilities.json. Do not edit; not committed.
/* eslint-disable */

export const schemaVersion = ${JSON.stringify(contract.version)};

${types.trim()}

${eventTypes.trim()}

${progressType.trim()}

export type CapabilityName = keyof Capabilities;
export type EventCapability = keyof CapabilityEvents;
export type EventType<N extends EventCapability> = keyof CapabilityEvents[N];
/** The payload of an event of capability N's stream. */
export type EventPayload<N extends EventCapability, T extends EventType<N>> = CapabilityEvents[N][T];

/** The topic each streaming capability's events carry. */
export const eventTopics = ${JSON.stringify(eventTopics, null, '\t')} as const satisfies Record<EventCapability, string>;

export type Params<N extends CapabilityName> = Capabilities[N]['params'];
export type Result<N extends CapabilityName> = Capabilities[N]['result'];

/** What the client branches on, per capability. */
export const capabilityInfo = ${JSON.stringify(info, null, '\t')} as const satisfies Record<
	CapabilityName,
	{ scope: 'global' | 'workspace'; longRunning: boolean; statefulness: 'stateless' | 'stateful' | 'streaming' }
>;
`;

mkdirSync(dirname(fileURLToPath(target)), { recursive: true });
writeFileSync(target, out);
console.log(`gen-client: ${contract.capabilities.length} capabilities, schema ${contract.version}`);
